CREATE TABLE IF NOT EXISTS "Fb" (
  "id" TEXT NOT NULL,
  "adminId" TEXT NOT NULL,
  "text" TEXT NOT NULL,
  "links" JSONB NOT NULL,
  "createdAt" TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP,
  "updatedAt" TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT "Fb_pkey" PRIMARY KEY ("id"),
  CONSTRAINT "Fb_adminId_fkey" FOREIGN KEY ("adminId") REFERENCES "users"("id") ON DELETE CASCADE ON UPDATE CASCADE
);

CREATE INDEX IF NOT EXISTS "Fb_adminId_createdAt_idx" ON "Fb"("adminId", "createdAt");
